export function formatSoles(value: number): string {
  return `S/ ${value.toLocaleString('en-US', {
    minimumFractionDigits: 2,
    maximumFractionDigits: 2,
  })}`;
}

export function formatKg(value: number): string {
  return `${value.toLocaleString('en-US', {
    maximumFractionDigits: 2,
  })} kg`;
}

export function calculateOrderTotals(
  items: { cantidadKg: number; precioKg: number }[],
  settings: CompanySettings
) {
  const subtotal = Number(
    items.reduce((acc, item) => acc + item.cantidadKg * item.precioKg, 0).toFixed(2)
  );
  const qualifiesDiscount = subtotal >= settings.montoMinimoDescuentoSoles;
  const descuento = qualifiesDiscount
    ? Number(((subtotal * settings.porcentajeDescuento) / 100).toFixed(2))
    : 0;
  const total = Number((subtotal - descuento).toFixed(2));
  const meetsMinimum = subtotal >= settings.pedidoMinimoSoles;

  return {
    subtotal,
    descuento,
    total,
    qualifiesDiscount,
    meetsMinimum,
  };
}
